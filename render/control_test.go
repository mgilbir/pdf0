// TestApproximatedControlsAreReported pins the finding that says a box is
// standing in for a widget, and — as importantly — pins where it does *not*
// fire. A rule that fired on every control would be noise, and noise is how a
// report stops being read.
func TestApproximatedControlsAreReported(t *testing.T) {
	quiet := []string{
		`<input type=text value=x>`,
		`<input type=password value=x>`,
		`<input type=submit value=go>`,
		`<button>go</button>`,
		`<textarea>words</textarea>`,
		`<input type=checkbox>`,
		`<input type=radio>`,
	}
	for _, markup := range quiet {
		built := controlBuild(t, markup)
		if got := findingsWith(built.Findings, RuleControlApproximated); len(got) != 0 {
			t.Errorf("%s was reported as approximated: %s", markup, got[0].Error())
		}
	}

	loud := []string{
		`<input type=file>`,
		`<input type=range>`,
		`<input type=color>`,
		`<input type=image src=x.png>`,
		// A checked box is drawn as an empty square, and the mark inside it is
		// the thing that cannot be drawn — so the state is what makes this
		// report, not the element.
		`<input type=checkbox checked>`,
		`<input type=radio checked>`,
	}
	for _, markup := range loud {
		built := controlBuild(t, markup)
		if got := findingsWith(built.Findings, RuleControlApproximated); len(got) == 0 {
			t.Errorf("%s was drawn as a plain box and said nothing: %v", markup, built.Findings)
			continue
		}
		fired[RuleControlApproximated] = true
	}
}

