package pdfa

import (
	"crypto/md5"
	"fmt"
	"github.com/mgilbir/pdf0/object"
	"time"

	lcms2 "github.com/mgilbir/golittlecms"
)

// This file builds conforming PDF/A documents rather than checking them: the
// minimal five-object skeleton (catalog, page tree, XMP metadata stream,
// output intent, ICC profile) that satisfies the ISO 19005 identification and
// output-intent requirements at every level, the pdfaid identification XMP
// packet (metadata clause 6.7 in ISO 19005-1, 6.6.2 in -2/-3), and the PDF
// version each part is defined against (1.4 for -1, 1.7 for -2/-3, 2.0 for -4).
//
// The sRGB destination profile is a genuine ICC profile generated by
// golittlecms, not a hand-assembled stub, and its version is chosen by level:
// PDF/A-1 targets PDF 1.4, which admits only ICC v2, so it gets v2.1 while the
// later parts get v4. Anything produced here must pass pdf0's own validator —
// the round trip through ValidatePDFA is what keeps the two sides honest.

// Skeleton returns the minimal five-object graph a conforming PDF/A file needs
// — catalog, page tree, XMP metadata, output intent, ICC profile — with the
// trailer and the header version that part is defined against.
//
// It returns the graph rather than a Document so that both sides can use it:
// NewPDFADocumentWithInfo wraps it into one, and this package's own tests wrap
// it into a view without needing the document type at all.
func Skeleton(level Level, title, author string) (map[int]*object.IndirectObject, object.Dictionary, string) {
	version := pdfaVersion(level)

	// Generate file ID
	now := time.Now().Format(time.RFC3339Nano)
	hash := md5.Sum([]byte("pdf0-pdfa-" + now))
	fileID := object.String{Value: hash[:], IsHex: true}

	// Object 1: Catalog
	catalog := &object.Dictionary{}
	catalog.Set("Type", object.Name("Catalog"))
	catalog.Set("Pages", object.IndirectRef{Number: 2})
	catalog.Set("Metadata", object.IndirectRef{Number: 3})
	catalog.Set("OutputIntents", object.Array{object.IndirectRef{Number: 4}})
	if level.IsA() {
		// A Level A file is a Tagged PDF with a logical structure tree. The empty
		// page tree carries no content, so a minimal marked, empty structure tree
		// satisfies the structural requirement (audit C19).
		markInfo := &object.Dictionary{}
		markInfo.Set("Marked", object.Boolean(true))
		catalog.Set("MarkInfo", markInfo)
		structTreeRoot := &object.Dictionary{}
		structTreeRoot.Set("Type", object.Name("StructTreeRoot"))
		catalog.Set("StructTreeRoot", structTreeRoot)
	}

	// Object 2: Pages (empty page tree)
	pages := &object.Dictionary{}
	pages.Set("Type", object.Name("Pages"))
	pages.Set("Kids", object.Array{})
	pages.Set("Count", object.Integer(0))

	// Object 3: Metadata stream (XMP, unfiltered)
	xmpData := GenerateXMPMetadata(level, title, author)
	metaStream := &object.Stream{
		Dict: object.Dictionary{},
		Data: xmpData,
	}
	metaStream.Dict.Set("Type", object.Name("Metadata"))
	metaStream.Dict.Set("Subtype", object.Name("XML"))
	metaStream.Dict.Set("Length", object.Integer(len(xmpData)))

	// Object 4: OutputIntent dictionary
	outputIntent := &object.Dictionary{}
	outputIntent.Set("Type", object.Name("OutputIntent"))
	outputIntent.Set("S", object.Name("GTS_PDFA1"))
	outputIntent.Set("OutputConditionIdentifier", object.String{Value: []byte("sRGB IEC61966-2.1")})
	outputIntent.Set("RegistryName", object.String{Value: []byte("http://www.color.org")})
	outputIntent.Set("Info", object.String{Value: []byte("sRGB IEC61966-2.1")})
	outputIntent.Set("DestOutputProfile", object.IndirectRef{Number: 5})

	// Object 5: ICC profile stream
	iccData := sRGBProfile(level)
	iccStream := &object.Stream{
		Dict: object.Dictionary{},
		Data: iccData,
	}
	iccStream.Dict.Set("N", object.Integer(3)) // 3-component (RGB)
	iccStream.Dict.Set("Length", object.Integer(len(iccData)))

	return map[int]*object.IndirectObject{
			1: {Number: 1, Generation: 0, Value: catalog},
			2: {Number: 2, Generation: 0, Value: pages},
			3: {Number: 3, Generation: 0, Value: metaStream},
			4: {Number: 4, Generation: 0, Value: outputIntent},
			5: {Number: 5, Generation: 0, Value: iccStream},
		}, object.Dictionary{
			Keys: []object.Name{"Root", "ID"},
			Values: []object.Object{
				object.IndirectRef{Number: 1},
				object.Array{fileID, fileID},
			},
		}, version
}

func pdfaVersion(level Level) string {
	switch level.BaseB() {
	case PDFA1b:
		return "1.4"
	case PDFA2b, PDFA3b:
		return "1.7"
	default:
		return "2.0"
	}
}

func pdfaPart(level Level) int {
	switch level.BaseB() {
	case PDFA1b:
		return 1
	case PDFA2b:
		return 2
	case PDFA3b:
		return 3
	default:
		return 4
	}
}

func pdfaConformance(level Level) string {
	switch {
	case level.IsA():
		return "A"
	case level == PDFA4:
		return "" // PDF/A-4 has no conformance level
	default:
		return "B"
	}
}

// GenerateXMPMetadata creates XMP metadata bytes for the given PDF/A level.
func GenerateXMPMetadata(level Level, title, author string) []byte {
	part := pdfaPart(level)
	conformance := pdfaConformance(level)

	titleXMP := ""
	if title != "" {
		titleXMP = fmt.Sprintf(`
      <dc:title>
        <rdf:Alt>
          <rdf:li xml:lang="x-default">%s</rdf:li>
        </rdf:Alt>
      </dc:title>`, XMLEscape(title))
	}

	authorXMP := ""
	if author != "" {
		authorXMP = fmt.Sprintf(`
      <dc:creator>
        <rdf:Seq>
          <rdf:li>%s</rdf:li>
        </rdf:Seq>
      </dc:creator>`, XMLEscape(author))
	}

	conformanceXMP := ""
	if conformance != "" {
		conformanceXMP = fmt.Sprintf(`
      <pdfaid:conformance>%s</pdfaid:conformance>`, conformance)
	}

	revXMP := ""
	if level == PDFA4 {
		revXMP = `
      <pdfaid:rev>2020</pdfaid:rev>`
	}

	xmp := fmt.Sprintf(`<?xpacket begin="%s" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/">
  <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
    <rdf:Description rdf:about=""
      xmlns:dc="http://purl.org/dc/elements/1.1/"
      xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/"
      xmlns:xmp="http://ns.adobe.com/xap/1.0/">
      <pdfaid:part>%d</pdfaid:part>%s%s%s%s
      <xmp:CreatorTool>pdf0</xmp:CreatorTool>
    </rdf:Description>
  </rdf:RDF>
</x:xmpmeta>
<?xpacket end="w"?>`, "\xEF\xBB\xBF", part, conformanceXMP, revXMP, titleXMP, authorXMP)

	return []byte(xmp)
}

func XMLEscape(s string) string {
	var result []byte
	for _, b := range []byte(s) {
		switch b {
		case '<':
			result = append(result, []byte("&lt;")...)
		case '>':
			result = append(result, []byte("&gt;")...)
		case '&':
			result = append(result, []byte("&amp;")...)
		case '"':
			result = append(result, []byte("&quot;")...)
		case '\'':
			result = append(result, []byte("&apos;")...)
		default:
			// Control characters other than tab/LF/CR are illegal in XML
			// 1.0 even when escaped; passing them through produced
			// malformed XMP. Drop them.
			if b < 0x20 && b != '\t' && b != '\n' && b != '\r' {
				continue
			}
			result = append(result, b)
		}
	}
	return string(result)
}

// DefaultSRGBProfile returns a real sRGB ICC profile (ICC v2.1, valid at every
// PDF/A level) generated by golittlecms, a pure-Go Little CMS port. It is
// exported for callers that assemble their own OutputIntent; NewPDFADocument
// uses sRGBProfile to select a level-appropriate profile version.
func DefaultSRGBProfile() []byte {
	return sRGBProfile(PDFA1b)
}

// sRGBProfile builds an sRGB ICC profile suitable for the given PDF/A level.
// PDF/A-1 targets PDF 1.4, which permits only ICC v2 profiles, so it receives an
// ICC v2.1 profile; PDF/A-2/3/4 target PDF 1.7/2.0 and receive the compact ICC
// v4 profile. Both are genuine profiles emitted by — and re-readable through — a
// real colour-management engine.
func sRGBProfile(level Level) []byte {
	version := 4.3
	if level.BaseB() == PDFA1b {
		version = 2.1 // PDF/A-1 is based on PDF 1.4, which allows only ICC v2
	}
	data, err := buildSRGBProfile(version)
	if err != nil {
		// Create_sRGBProfile builds from fixed constants and SaveProfileToMem
		// writes to an in-memory buffer, so an error here is a library-internal
		// invariant failure rather than a runtime condition. Fail loudly.
		panic("pdf0: generating sRGB ICC profile: " + err.Error())
	}
	return data
}

// buildSRGBProfile generates an sRGB ICC profile serialized at the requested ICC
// version (e.g. 2.1 or 4.3) using golittlecms.
func buildSRGBProfile(version float64) ([]byte, error) {
	p, err := lcms2.Create_sRGBProfile()
	if err != nil {
		return nil, err
	}
	p.SetProfileVersion(version)
	return p.SaveProfileToMem()
}
